for (const [
  id,
  title,
  description,
  category,
  subcategory,
  tags,
  javaVersion,
  imports,
  code,
  notes,
  dependency,
] of snippets) {
  const meta = {
    id,
    title,
    description,
    category,
    subcategory,
    tags,
    javaVersion,
    ...(imports.length ? { imports } : {}),
    ...(dependency ? { dependency } : {}),
    ...(id === "files-read-text"
      ? { related: ["files-lines", "files-write-text"] }
      : {}),
  };
  const dir = `DefaultSnippets/${category.replace(/[^a-zA-Z0-9]/g, "")}`;
  mkdirSync(dir, { recursive: true });
  writeFileSync(
    `${dir}/${id}.md`,
    `---\n${stringify(meta, { lineWidth: 0 })}---\n\n\`\`\`java\n${code}\n\`\`\`\n\n## Notes\n\n${notes}\n`,
  );
}
